%%% Run tests based on provied cfg struct from test case function.

%% Get the cfg struct

addpath('TBD/Includes')
addpath('TBD/test/TBD_PF_test/config')

prompt = 'Select desired test case: T# ';
o = input(prompt);

switch o

    case {'T1','1','t1',1}
        cfg = T1_PF_Static_N5000_v0_s1();
    case {'T2','2','t2',2}
        cfg = T2_PF_Static_N5000_v15_s1();
    case {'T3','3','t3',3}
        cfg = T3_PF_Static_N5000_v15_s1();
    otherwise
        error("Unknown test case, look in TBD/test/TBD_PF_test/config for valid options")

end
fprintf("\n--------------TBD_PF_test--------- \n")
fprintf(cfg.description)
fprintf("\n---------------------------------- \n")

%%% Setup environment class
e = environment(...
    'Debug', cfg.env.Debug,...
    'Units', cfg.env.Units,...
    'Seed', cfg.env.Seed,...
    'obj',cfg.env.objs,...
    'kEnd',cfg.env.kEnd,...
    'dt',cfg.env.dt,...
    'trajectories',cfg.env.trajectories,...
    'rw',cfg.env.rw,...
    'start',cfg.env.start,...
    'final',cfg.env.final,...
    'kBirth',cfg.env.kBirth,...
    'kDeath',cfg.env.kDeath,...
    'Normalize',cfg.env.Normalize,...
    'Blur',cfg.env.Blur,...
    'Sigma',cfg.env.Sigma,...
    'Noise',cfg.env.Noise,...
    'Var',cfg.env.Var);

%%% Setup TBD filter that will be used (for when other filters are options)

switch cfg.filter
    case "TBD_PF"
        f = TBD_PF(...
            'Debug', cfg.TBD.Debug,...
            'Units', cfg.TBD.Units,...
            'Seed', cfg.TBD.Seed,...
            'STD', cfg.TBD.STD,...
            'Sigma', cfg.TBD.Sigma,...
            'dt', cfg.TBD.dt,...
            'Ip', cfg.TBD.Ip,...
            'Background', cfg.TBD.Background,...
            'N', cfg.TBD.N,...
            'Pb', cfg.TBD.Pb,...
            'Ps', cfg.TBD.Ps,...
            'pEthresh', cfg.TBD.pEthresh,...
            'pDist', cfg.TBD.pDist,...
            'Q', cfg.TBD.Q,...
            'v_max', cfg.TBD.v_max,...
            'v_min', cfg.TBD.v_min,...
            'gamma', cfg.TBD.gamma);
end

%%% Build the environment
scenario = e.setup();


%%% Run the filter
%%% TODO: Changes when we run multiple filters in one test case

R = f.run(scenario,...
      'Bootstrap', cfg.run.Bootstrap,...
      'ESS', cfg.run.ESS,...
      'Likelihood', cfg.run.Likelihood,...
      'Var', cfg.run.Var,...
      'DebugPlots', cfg.run.DebugPlots,...
      'DebugFrames', cfg.run.DebugFrames);

% plot
[f1, f2] = f.show(R, scenario,'Animate',cfg.show.Animate,...
'Save',cfg.show.Save,...
'ShowBirths', cfg.show.ShowBirths);